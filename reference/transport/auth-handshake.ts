export type HandshakeError =
  | "ADV_VERIFICATION_FAILED"
  | "PROOF_INVALID"
  | "WRONG_ROLE"
  | "WRONG_LINK_ID"
  | "CHALLENGE_EXPIRED"
  | "CHALLENGE_REPLAYED"
  | "CHALLENGE_NOT_FOUND"
  | "PEER_DENYLISTED"
  | "MALFORMED_MESSAGE";

export interface LinkUpRecord {
  linkIdBytes: Uint8Array;
  linkIdHex: string;
  localNodeId: string;
  remoteNodeId: string;
  remotePublicKey: Uint8Array;
  remoteCapabilities: readonly string[];
  establishedAt: number;
}

/**
 * Build the Initiate message (step 1).
 * Called by the initiator.
 */
export function buildInitiate(
  localAdvertisement: NodeAdvertisement,
  linkNonceA: Uint8Array,
  challengeForB: Uint8Array,
): InitiateMessage {
  if (linkNonceA.length !== LINK_NONCE_BYTES) throw new Error("linkNonceA must be 16 bytes");
  if (challengeForB.length !== CHALLENGE_BYTES) throw new Error("challengeForB must be 32 bytes");
  return {
    kind: MSG_KIND.INITIATE,
    advertisementHex: toHex(canonicalEncode(advertisementToCborHex(localAdvertisement))),
    linkNonceA,
    challengeForB,
  };
}

/** Helper: convert a NodeAdvertisement to its canonical CBOR hex. */
function advertisementToCborHex(adv: NodeAdvertisement): Map<number, unknown> {
  // This is a placeholder — the actual encoding is in advertisement.ts
  // For the handshake, we pass the hex string directly.
  return new Map();
}

/**
 * Process an Initiate message and build the Accept message (step 2).
 * Called by the responder.
 *
 * Verifies A's advertisement, generates B's nonce + challenge, computes the
 * transcript hash, signs B's possession proof, and returns the Accept message.
 */
export function processInitiateAndBuildAccept(
  initiateBytes: Uint8Array,
  localAdvertisement: NodeAdvertisement,
  localKeypair: NodeKeypair,
  linkNonceB: Uint8Array,
  challengeForA: Uint8Array,
  referenceNow: number,
): { ok: true; accept: Uint8Array; remoteAdv: NodeAdvertisement; linkIdBytes: Uint8Array } | { ok: false; error: HandshakeError; detail: string } {
  // Decode the Initiate message
  let initiate: InitiateMessage;
  try {
    initiate = decodeMessage(initiateBytes) as InitiateMessage;
    if (initiate.kind !== MSG_KIND.INITIATE) {
      return { ok: false, error: "MALFORMED_MESSAGE", detail: "expected INITIATE" };
    }
  } catch (e) {
    return { ok: false, error: "MALFORMED_MESSAGE", detail: (e as Error).message };
  }

  // Verify A's advertisement
  // We need to parse the advertisement from hex. Import lazily to avoid circular deps.
  let remoteAdv: NodeAdvertisement;
  try {
    remoteAdv = advertisementFromHex(initiate.advertisementHex);
  } catch (e) {
    return { ok: false, error: "ADV_VERIFICATION_FAILED", detail: `decode: ${(e as Error).message}` };
  }

  const v = verifyAdvertisement(remoteAdv, referenceNow);
  if (!v.ok) {
    return { ok: false, error: "ADV_VERIFICATION_FAILED", detail: v.detail };
  }

  // Compute LinkId bytes (directional: local=B, remote=A)
  const linkIdBytes = computeLinkIdBytes(
    localKeypair.nodeId,
    remoteAdv.nodeId,
    linkNonceB,
    initiate.linkNonceA,
  );

  // Compute transcript hash (just the Initiate message so far)
  const transcriptHash = computeTranscriptHash([initiateBytes]);

  // B signs the challenge generated by A (initiate.challengeForB)
  const proofB = signPossessionProof(
    localKeypair.secretKey,
    POSSESSION_DOMAIN_RESPONDER,
    transcriptHash,
    linkIdBytes,
    initiate.challengeForB,
    ROLE_RESPONDER,
  );

  // Build the Accept message
  const accept: AcceptMessage = {
    kind: MSG_KIND.ACCEPT,
    advertisementHex: toHex(fromHex(localAdvertisementHex(localAdvertisement))),
    linkNonceB,
    challengeForA,
    proofB,
  };

  const acceptBytes = encodeAccept(accept);
  return { ok: true, accept: acceptBytes, remoteAdv, linkIdBytes };
}

/** Helper: get the canonical CBOR hex of a local advertisement. */
function localAdvertisementHex(adv: NodeAdvertisement): string {
  // Re-export from advertisement module
  return advertisementToHex(adv);
}

/**
 * Process an Accept message and build the Confirm message (step 3).
 * Called by the initiator.
 *
 * Verifies B's advertisement + B's possession proof, then signs A's possession proof.
 */
export function processAcceptAndBuildConfirm(
  initiateBytes: Uint8Array,
  acceptBytes: Uint8Array,
  localKeypair: NodeKeypair,
  localAdvertisement: NodeAdvertisement,
  initiateLinkNonceA: Uint8Array,
  initiateChallengeForB: Uint8Array,
  referenceNow: number,
): { ok: true; confirm: Uint8Array; remoteAdv: NodeAdvertisement; linkIdBytes: Uint8Array } | { ok: false; error: HandshakeError; detail: string } {
  // Decode the Accept message
  let accept: AcceptMessage;
  try {
    accept = decodeMessage(acceptBytes) as AcceptMessage;
    if (accept.kind !== MSG_KIND.ACCEPT) {
      return { ok: false, error: "MALFORMED_MESSAGE", detail: "expected ACCEPT" };
    }
  } catch (e) {
    return { ok: false, error: "MALFORMED_MESSAGE", detail: (e as Error).message };
  }

  // Verify B's advertisement
  let remoteAdv: NodeAdvertisement;
  try {
    remoteAdv = advertisementFromHex(accept.advertisementHex);
  } catch (e) {
    return { ok: false, error: "ADV_VERIFICATION_FAILED", detail: `decode: ${(e as Error).message}` };
  }

  const v = verifyAdvertisement(remoteAdv, referenceNow);
  if (!v.ok) {
    return { ok: false, error: "ADV_VERIFICATION_FAILED", detail: v.detail };
  }

  // Compute LinkId bytes (directional: local=A, remote=B)
  const linkIdBytes = computeLinkIdBytes(
    localKeypair.nodeId,
    remoteAdv.nodeId,
    initiateLinkNonceA,
    accept.linkNonceB,
  );

  // Compute transcript hash (Initiate + Accept)
  const transcriptHash = computeTranscriptHash([initiateBytes, acceptBytes]);

  // Verify B's possession proof
  // B signed: challenge_for_B (generated by A), with role RESPONDER
  const proofOk = verifyPossessionProof(
    remoteAdv.signingPublicKey,
    accept.proofB,
    POSSESSION_DOMAIN_RESPONDER,
    transcriptHash,
    linkIdBytes,
    initiateChallengeForB,
    ROLE_RESPONDER,
  );
  if (!proofOk) {
    return { ok: false, error: "PROOF_INVALID", detail: "B's possession proof did not verify" };
  }

  // A signs the challenge generated by B (accept.challengeForA)
  const proofA = signPossessionProof(
    localKeypair.secretKey,
    POSSESSION_DOMAIN_INITIATOR,
    transcriptHash,
    linkIdBytes,
    accept.challengeForA,
    ROLE_INITIATOR,
  );

  const confirm: ConfirmMessage = { kind: MSG_KIND.CONFIRM, proofA };
  const confirmBytes = encodeConfirm(confirm);
  return { ok: true, confirm: confirmBytes, remoteAdv, linkIdBytes };
}

/**
 * Process a Confirm message (step 3, responder side).
 * Verifies A's possession proof. If valid, LINK_UP is established.
 */
export function processConfirm(
  initiateBytes: Uint8Array,
  acceptBytes: Uint8Array,
  confirmBytes: Uint8Array,
  responderKeypair: NodeKeypair,
  initiatorAdv: NodeAdvertisement,
  linkNonceB: Uint8Array,
  linkNonceA: Uint8Array,
  challengeForA: Uint8Array,
  referenceNow: number,
): { ok: true; linkUp: LinkUpRecord } | { ok: false; error: HandshakeError; detail: string } {
  // Decode the Confirm message
  let confirm: ConfirmMessage;
  try {
    confirm = decodeMessage(confirmBytes) as ConfirmMessage;
    if (confirm.kind !== MSG_KIND.CONFIRM) {
      return { ok: false, error: "MALFORMED_MESSAGE", detail: "expected CONFIRM" };
    }
  } catch (e) {
    return { ok: false, error: "MALFORMED_MESSAGE", detail: (e as Error).message };
  }

  // Compute LinkId bytes (directional: local=B, remote=A)
  const linkIdBytes = computeLinkIdBytes(
    responderKeypair.nodeId,
    initiatorAdv.nodeId,
    linkNonceB,
    linkNonceA,
  );

  // Compute transcript hash (Initiate + Accept)
  const transcriptHash = computeTranscriptHash([initiateBytes, acceptBytes]);

  // Verify A's possession proof
  // A signed: challenge_for_A (generated by B), with role INITIATOR
  const proofOk = verifyPossessionProof(
    initiatorAdv.signingPublicKey,
    confirm.proofA,
    POSSESSION_DOMAIN_INITIATOR,
    transcriptHash,
    linkIdBytes,
    challengeForA,
    ROLE_INITIATOR,
  );
  if (!proofOk) {
    return { ok: false, error: "PROOF_INVALID", detail: "A's possession proof did not verify" };
  }

  // Both proofs verified — LINK_UP established
  return {
    ok: true,
    linkUp: {
      linkIdBytes,
      linkIdHex: toHex(linkIdBytes),
      localNodeId: responderKeypair.nodeId,
      remoteNodeId: initiatorAdv.nodeId,
      remotePublicKey: initiatorAdv.signingPublicKey,
      remoteCapabilities: initiatorAdv.capabilities,
      establishedAt: Date.now(),
    },
  };
}

