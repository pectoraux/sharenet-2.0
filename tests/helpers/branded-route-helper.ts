/**
 * ShareNet 2.0 — Shared test helper: genuine BrandedCommittedRoute pipeline.
 *
 * Per R-002-P1 + R-006 construction-boundary fix: the full proof-carrying
 * pipeline now runs a genuine 3-message handshake per hop, producing a
 * VerifiedTranscript + AuthenticatedLink before each ValidatedHop:
 *
 *   generateNodeKeypair (per hop + initiator)
 *       ↓
 *   signAdvertisement → verifyAdvertisement → VerifiedNodeAdvertisement (WeakSet)
 *       ↓
 *   createAuthenticatedNodeRecord → AuthenticatedNodeRecord (WeakSet)
 *       ↓
 *   3-message handshake (Initiate → Accept → Confirm)
 *       ↓
 *   createVerifiedTranscript (verifies BOTH possession proofs) → VerifiedTranscript (WeakSet)
 *       ↓
 *   createAuthenticatedLink → AuthenticatedLink (WeakSet)
 *       ↓
 *   createValidatedHop(link, ...) → ValidatedHop (WeakSet)
 *       ↓
 *   RouteProposal (RouteHop[] derived from the same fields)
 *       ↓
 *   signRouteAcceptance × N
 *       ↓
 *   createRouteCommitment → RouteCommitment (WeakSet)
 *       ↓
 *   createBrandedCommittedRoute(commitment, validatedHops) → BrandedCommittedRoute (WeakSet)
 */

