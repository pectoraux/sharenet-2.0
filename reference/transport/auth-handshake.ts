/**
 * ShareNet 2.0 — Authenticated Link Handshake (3-message, transcript-bound).
 *
 * Per ADR-0016 (RESOLVED — Principal Architect approved via roadmap §B):
 *
 *   The current two-message exchange is only ADV_VERIFIED, never LINK_UP.
 *   Implement authenticated links only using this three-message design:
 *
 *   1. Initiator → Responder, Initiate
 *      - canonical advertisement bytes for A
 *      - link_nonce_A: 16 random bytes
 *      - challenge_for_B: 32 random bytes
 *
 *   2. Responder → Initiator, Accept
 *      - canonical advertisement bytes for B
 *      - link_nonce_B: 16 random bytes
 *      - challenge_for_A: 32 random bytes
 *      - proof_B: Ed25519 signature by B over B's possession payload
 *
 *   3. Initiator → Responder, Confirm
 *      - proof_A: Ed25519 signature by A over A's possession payload
 *
 * Transcript framing:
 *   transcript_hash = BLAKE3-256(
 *     utf8("SHARENET/LINK/TRANSCRIPT/1")
 *     || u32be(length(message_1)) || message_1
 *     || u32be(length(message_2)) || message_2
 *     || ...
 *   )
 *
 * Possession payload (what each party signs):
 *   utf8(role-specific domain tag)
 *   || transcript_hash           (32 bytes)
 *   || directional_link_id_bytes (32 bytes)
 *   || peer_generated_challenge  (32 bytes)
 *   || role_byte                 (1 byte: 0x01 = INITIATOR, 0x02 = RESPONDER)
 *
 * Domain tags:
 *   SHARENET/LINK/POSSESSION/INITIATOR/1
 *   SHARENET/LINK/POSSESSION/RESPONDER/1
 *
 * Rules:
 *   - Each party signs the challenge generated by the peer, never its own.
 *   - A LINK_UP record exists only after both proofs verify.
 *   - ADV_VERIFIED is not routable.
 */

